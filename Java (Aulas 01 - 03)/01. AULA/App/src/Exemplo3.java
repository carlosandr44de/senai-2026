public class Exemplo3 {

    public static void main(String[] args) {
        int numero1 = 1000, numero2 = 5000;
        // mover texto --> alt + seta (cima ou baixo) em um texto selecionado ou apenas uma linha
        if (numero1 > numero2){
            //shift + alt + seta pra baixo
            System.out.println("O número maior é: "+numero1);
        }
        else
        {
            System.out.println("O número maior é: "+numero2);
        }
    }
}
        